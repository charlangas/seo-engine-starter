"""Deterministic text helpers shared by every stage."""
from __future__ import annotations

import re
import unicodedata

import yaml

import lang

STOPWORDS = {
    "a", "an", "the", "of", "to", "for", "in", "on", "and", "or", "is", "are", "was", "be",
    "your", "you", "with", "do", "does", "it", "its", "can", "i", "my", "we", "our", "this",
    "that", "at", "by", "from", "as", "me", "near", "vs", "about", "should", "will", "s",
}

# Banned phrases: exact match, case-insensitive (apostrophes normalised first).
BANNED_PHRASES = [
    "in today's digital landscape", "unlock", "leverage", "delve", "it's important to note",
    "in conclusion", "in the realm of", "harness the power", "cutting-edge", "seamless", "robust",
]

# Deterministic last-resort swaps so a banned phrase can never survive revision.
BANNED_REPLACEMENTS = {
    "in today's digital landscape": "right now",
    "unlock": "open up",
    "leverage": "use",
    "delve": "dig",
    "it's important to note": "note",
    "in conclusion": "so",
    "in the realm of": "in",
    "harness the power": "make use",
    "cutting-edge": "newest",
    "seamless": "smooth",
    "robust": "sturdy",
}

DISCLOSURE_PATTERNS = [
    r"\bas an ai\b", r"\bas a language model\b", r"\bai[- ]generated\b", r"\bgenerated by ai\b",
    r"\bwritten by ai\b", r"\bthis (article|post|content) was (generated|written|created) (by|with|using)\b",
    r"\bi am an ai\b", r"\blarge language model\b",
]

PLACEHOLDER_PATTERNS = [r"\bTODO\b", r"\bTBD\b", r"\[[a-z_ ]{2,30}\](?!\()", r"lorem ipsum", r"\bXXX\b", r"\{[a-z_]+\}"]


def normalize_quotes(text: str) -> str:
    return (text.replace("’", "'").replace("‘", "'")
            .replace("“", '"').replace("”", '"'))


def slugify(text: str) -> str:
    text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    text = re.sub(r"[^a-zA-Z0-9]+", "-", text.lower()).strip("-")
    return text[:80].strip("-") or "untitled"


def fold(text: str) -> str:
    """Strip accents (suspensión -> suspension). Used for Spanish matching only."""
    return "".join(c for c in unicodedata.normalize("NFKD", text) if not unicodedata.combining(c))


def _stem_es(token: str) -> str:
    if len(token) > 4 and token.endswith("ces"):
        return token[:-3] + "z"
    if len(token) > 4 and token.endswith("es") and token[-3] in "rlndjy":
        return token[:-2]
    if len(token) > 3 and token.endswith("s"):
        return token[:-1]
    return token


def stem(token: str) -> str:
    if lang.is_es():
        return _stem_es(token)
    if len(token) > 4 and token.endswith("ies"):
        return token[:-3] + "y"
    if len(token) > 3 and token.endswith("s") and not token.endswith("ss"):
        return token[:-1]
    return token


def tokens(text: str, drop_stop: bool = True) -> list[str]:
    if lang.is_es():
        raw = re.findall(r"[a-z0-9]+", fold(normalize_quotes(text).lower()))
        if drop_stop:
            raw = [t for t in raw if t not in lang.ES_STOPWORDS]
        return [stem(t) for t in raw]
    raw = re.findall(r"[a-z0-9]+", normalize_quotes(text).lower())
    out = [stem(t) for t in raw]
    if drop_stop:
        out = [t for t in out if t not in STOPWORDS]
    return out


def normalize_keyword(keyword: str) -> str:
    """Lowercase, strip punctuation, stem plurals, drop stopwords, sort tokens."""
    return " ".join(sorted(tokens(keyword)))


def levenshtein(a: str, b: str) -> int:
    if a == b:
        return 0
    if not a or not b:
        return len(a) or len(b)
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1]


def similarity(a: str, b: str) -> float:
    """Normalised Levenshtein similarity in [0, 1] on normalised keywords."""
    na, nb = normalize_keyword(a), normalize_keyword(b)
    if not na or not nb:
        return 0.0
    return 1.0 - levenshtein(na, nb) / max(len(na), len(nb))


def jaccard(a, b) -> float:
    a, b = set(a), set(b)
    return len(a & b) / len(a | b) if a and b else 0.0


def word_count(text: str) -> int:
    if lang.is_es():
        return len(re.findall(r"[^\W_][\w'’\-]*", text))
    return len(re.findall(r"[A-Za-z0-9][A-Za-z0-9'’\-]*", text))


def banned_phrases() -> list[str]:
    return lang.ES_BANNED_PHRASES if lang.is_es() else BANNED_PHRASES


def disclosure_patterns() -> list[str]:
    return DISCLOSURE_PATTERNS + lang.ES_DISCLOSURE_PATTERNS if lang.is_es() else DISCLOSURE_PATTERNS


def is_faq_heading(text: str) -> bool:
    pat = r"^(preguntas frecuentes|faq)" if lang.is_es() else r"^(frequently asked|faq)"
    return re.match(pat, text.strip(), re.I) is not None


def find_banned(text: str) -> list[str]:
    low = normalize_quotes(text).lower()
    if lang.is_es():
        return [p for p in lang.ES_BANNED_PHRASES if p in low]
    return [p for p in BANNED_PHRASES if p in low]


def scrub_banned(text: str) -> str:
    text = normalize_quotes(text)
    table = lang.ES_BANNED_REPLACEMENTS if lang.is_es() else BANNED_REPLACEMENTS
    for phrase, repl in table.items():
        def _sub(m, repl=repl):
            return repl.capitalize() if m.group(0)[0].isupper() else repl
        text = re.sub(re.escape(phrase), _sub, text, flags=re.I)
    return text


def title_case(text: str) -> str:
    if lang.is_es():  # Spanish headings use sentence case
        return smart_cap(text)
    small = {"a", "an", "the", "of", "to", "for", "in", "on", "and", "or", "vs", "at", "by", "with"}
    words = text.split()
    return " ".join(w if (i and w.lower() in small) else w[:1].upper() + w[1:] for i, w in enumerate(words))


def split_frontmatter(md: str) -> tuple[dict, str]:
    m = re.match(r"^---\n(.*?)\n---\n?(.*)$", md, flags=re.S)
    if not m:
        return {}, md
    try:
        fm = yaml.safe_load(m.group(1)) or {}
    except yaml.YAMLError:
        fm = {}
    return (fm if isinstance(fm, dict) else {}), m.group(2)


def build_frontmatter(fm: dict) -> str:
    return "---\n" + yaml.safe_dump(fm, sort_keys=False, allow_unicode=True, width=1000).strip() + "\n---\n"


def plain_text(md_body: str) -> str:
    """Markdown -> rough plain text (keeps anchor text, drops URLs and syntax)."""
    t = re.sub(r"```.*?```", " ", md_body, flags=re.S)
    t = re.sub(r"!\[[^\]]*\]\([^)]*\)", " ", t)
    t = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", t)
    t = re.sub(r"^\s*\|?[\s:|-]+\|[\s:|-]*$", " ", t, flags=re.M)
    t = re.sub(r"[#>*_`|]", " ", t)
    return re.sub(r"[ \t]+", " ", t)


def body_word_count(md: str) -> int:
    return word_count(plain_text(split_frontmatter(md)[1]))


def split_sections(body: str) -> tuple[str, str, list[dict]]:
    """Return (h1, intro, sections) where sections = [{'h2': str, 'text': str}]."""
    h1, intro, sections, cur = "", [], [], None
    in_code = False
    for line in body.splitlines():
        if line.strip().startswith("```"):
            in_code = not in_code
        if not in_code and re.match(r"^#\s+\S", line) and not h1:
            h1 = line[1:].strip()
            continue
        if not in_code and re.match(r"^##\s+\S", line):
            cur = {"h2": line[2:].strip(), "lines": []}
            sections.append(cur)
            continue
        (cur["lines"] if cur else intro).append(line)
    out = [{"h2": s["h2"], "text": "\n".join(s["lines"]).strip()} for s in sections]
    return h1, "\n".join(intro).strip(), out


def contains_keyword(text: str, keyword: str) -> bool:
    """Case-insensitive phrase match, tolerant of punctuation/hyphens between words."""
    if lang.is_es():
        # Spanish keywords are typed without accents or connectors ("amortiguadores guadalajara");
        # natural copy has both ("amortiguadores en Guadalajara"). Allow up to two connectors between words.
        conn = ["de", "del", "en", "para", "el", "la", "los", "las", "un", "una", "y", "a", "al", "por", "con",
                "tu", "tus", "su", "sus", "mi", "mis"]
        words = re.findall(r"[a-z0-9]+", fold(normalize_quotes(keyword).lower()))
        words = [w for w in words if w not in conn] or words
        if not words:
            return False
        gap = r"[\W_]+(?:(?:" + "|".join(conn) + r")[\W_]+){0,2}"
        pattern = r"\b" + gap.join(re.escape(w) for w in words) + r"\b"
        return re.search(pattern, fold(normalize_quotes(text).lower())) is not None
    words = re.findall(r"[a-z0-9]+", normalize_quotes(keyword).lower())
    if not words:
        return False
    pattern = r"\b" + r"[\W_]+".join(re.escape(w) for w in words) + r"\b"
    return re.search(pattern, normalize_quotes(text).lower()) is not None


ACRONYMS = {"b2b", "b2c", "seo", "ppc", "crm", "hvac", "saas", "roi", "ai", "cnc", "erp", "oem", "usa", "uk",
            "diy", "led", "api", "kpi", "abm", "cro", "ugc", "faq", "pr", "it", "hr", "ac", "tv", "3d"}


def smart_cap(text: str) -> str:
    """Capitalise the first letter and restore common acronyms (b2b -> B2B)."""
    acr = (ACRONYMS - {"it", "ac", "pr", "hr", "ai"}) | lang.ES_ACRONYMS if lang.is_es() else ACRONYMS - {"it"}
    words = [w.upper() if w.lower() in acr else w for w in text.split(" ")]
    out = " ".join(words)
    return out[:1].upper() + out[1:]


# --- Years -----------------------------------------------------------------------------------------
# Content is written for the year ahead and never names an earlier one: from October the engine writes
# for next year (in November 2026 that is 2027). `content_year: 2027` in a config pins it.
YEAR_RE = re.compile(r"(?<![\d.,$])(20\d\d)(?![\d%])")


def content_year(config: dict | None = None, today=None) -> int:
    from datetime import date
    pinned = (config or {}).get("content_year")
    if pinned and str(pinned).lower() != "auto":
        return int(pinned)
    today = today or date.today()
    return today.year + 1 if today.month >= 10 else today.year


def past_years(text: str, year: int) -> list[str]:
    """Years before `year` named in the text, ignoring link URLs, image paths and code (a cited URL may hold a date)."""
    t = re.sub(r"```.*?```|`[^`]*`", " ", text, flags=re.S)
    t = re.sub(r"\]\([^)]*\)", "]", t)
    t = re.sub(r"https?://\S+", " ", t)
    return sorted({y for y in YEAR_RE.findall(t) if int(y) < year})


def has_past_year(keyword: str, year: int) -> bool:
    return bool(past_years(keyword, year))


def drop_past_years(text: str, year: int) -> str:
    """Delete earlier years from prose (with a leading "in"/"across"/"since"... and a month name); links are kept.
    A blunt fallback for the template writer: the LLM writer rephrases instead."""
    months = r"(?:jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*\.?"

    def strip(seg: str) -> str:
        pat = re.compile(rf"(?:,?\s+(?:in|across|during|since|from|for|of|by)\s+)?(?:{months}\s+)?(?<![\d.,$])(20\d\d)(?![\d%])",
                         re.I)
        seg = re.sub(r"(?<![\d.,$])(20\d\d)\s*[-–]\s*(20\d\d)(?![\d%])",
                     lambda m: m.group(0) if int(m.group(2)) >= year else str(year + 9999), seg)  # whole range
        seg = pat.sub(lambda m: m.group(0) if int(m.group(1)) >= year else "", seg)
        seg = re.sub(rf"\s*\b{year + 9999}\b\s*", " ", seg)
        seg = re.sub(r"[ \t]{2,}", " ", seg)
        seg = re.sub(r"\s+([,.;:?!)])", r"\1", seg)
        return re.sub(r",\s*$", "", re.sub(r",(\s*[.;:?!])", r"\1", seg), flags=re.M)

    parts = re.split(r"(```.*?```|`[^`]*`|\]\([^)]*\)|https?://\S+)", text, flags=re.S)
    return "".join(p if i % 2 else strip(p) for i, p in enumerate(parts))
